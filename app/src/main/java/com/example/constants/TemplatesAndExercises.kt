    // Programmatic generation of 170+ exercises to meet specifications
    // Combines master lists with variation techniques (Halteres, Barra, Máquina, Cross, Unilateral, Inclinado, Declinado, etc.)
    val ALL_EXERCISES: List<Exercise> by lazy {
        val list = BASE_EXERCISES.toMutableList()
        val variations = listOf(
            "com Halteres", "com Barra", "na Máquina", "no Cross", "Unilateral", 
            "Inclinado", "Declinado", "com Elástico", "Isométrico", "Pegada Invertida", "no Smith"
        )
        val categories = listOf("Peito", "Costas", "Pernas", "Ombros", "Bíceps", "Tríceps", "Trapézio", "Abdominais")
        
        var idCounter = 100
        for (category in categories) {
            val categoryBases = BASE_EXERCISES.filter { it.category == category }
            if (categoryBases.isNotEmpty()) {
                for (base in categoryBases) {
                    for (variation in variations) {
                        val baseNameLower = base.name.lowercase()
                        val variationLower = variation.lowercase()
                        
                        // Enforce standard Brazilian gym terminology & eliminate conflicting modifiers
                        var isConflicting = false
                        
                        // Check angle/mechanical conflicts (e.g. Supino Reto cannot also be Inclinado/Declinado)
                        if (baseNameLower.contains("reto") && (variationLower.contains("inclinado") || variationLower.contains("declinado"))) {
                            isConflicting = true
                        }
                        if (baseNameLower.contains("inclinado") && (variationLower.contains("inclinado") || variationLower.contains("declinado"))) {
                            isConflicting = true
                        }
                        if (baseNameLower.contains("declinado") && (variationLower.contains("inclinado") || variationLower.contains("declinado"))) {
                            isConflicting = true
                        }
                        
                        // Check free weight vs machine/guided conflicts (e.g. Agachamento Livre cannot be Smith/Machine)
                        if (baseNameLower.contains("livre") && (variationLower.contains("máquina") || variationLower.contains("smith") || variationLower.contains("cross") || variationLower.contains("polia") || variationLower.contains("pulley"))) {
                            isConflicting = true
                        }
                        
                        // Bodyweight / Calisthenics conflicts (e.g. Abdominal Crunch Solo / Barra Fixa Pronada cannot be Smith/Machine/Halteres/Barra)
                        if ((baseNameLower.contains("solo") || baseNameLower.contains("suspenso") || baseNameLower.contains("fixa") || baseNameLower.contains("flexão") || baseNameLower.contains("mergulho") || baseNameLower.contains("prancha")) &&
                            (variationLower.contains("halteres") || variationLower.contains("barra") || variationLower.contains("máquina") || variationLower.contains("smith") || variationLower.contains("cross"))
                        ) {
                            isConflicting = true
                        }
                        
                        // Avoid generating redundant variations for explicit brand/plate-loaded machines
                        if (baseNameLower.contains("total health") || baseNameLower.contains("máquina anilhas") || baseNameLower.contains("na polia") || baseNameLower.contains("torre de placas") || baseNameLower.contains("standing hip thrust")) {
                            isConflicting = true
                        }
                        if (isConflicting) continue
                        
                        val newName = "${base.name.replace(" Barra", "").replace(" Halteres", "").replace(" Polia", "")} $variation"
                        if (newName != base.name) {
                            val derivedDifficulty = if (variation.contains("Smith") || variation.contains("Unilateral")) "Avançado" else base.difficulty
                            val derivedUnilateral = base.isUnilateral || variation.contains("Unilateral")
                            val derivedEquipmentType = when {
                                variation.contains("Halteres") -> EquipmentType.DUMBBELL
                                variation.contains("Barra") -> EquipmentType.BARBELL
                                variation.contains("Máquina") || variation.contains("na Máquina") -> EquipmentType.MACHINE
                                variation.contains("no Cross") || variation.contains("Polia") || variation.contains("Pulley") || variation.contains("Corda") -> EquipmentType.CABLE
                                variation.contains("no Smith") || variation.contains("Smith") -> EquipmentType.SMITH
                                variation.contains("com Elástico") || variation.contains("Elástico") -> EquipmentType.BAND
                                else -> base.equipmentTypes.firstOrNull() ?: EquipmentType.BODYWEIGHT
                            }
                            
                            list.add(
                                base.copy(
                                    id = "${category.lowercase()}_$idCounter",
                                    name = newName,
                                    category = category,
                                    description = "Variação do clássico ${base.name} - $variation.",
                                    difficulty = derivedDifficulty,
                                    isCustom = false,
                                    isUnilateral = derivedUnilateral,
                                    unilateral = derivedUnilateral,
                                    bilateral = !derivedUnilateral,
                                    equipmentTypes = listOf(derivedEquipmentType),
                                    equipment = when (derivedEquipmentType) {
                                        EquipmentType.BARBELL -> "Barra"
                                        EquipmentType.DUMBBELL -> "Halteres"
                                        EquipmentType.CABLE -> "Polia"
                                        EquipmentType.MACHINE -> "Máquina"
                                        EquipmentType.SMITH -> "Máquina"
                                        EquipmentType.BODYWEIGHT -> "Peso Corporal"
                                        else -> "Outros"
                                    }
                                )
                            )
                            idCounter++
                        }
                    }
                }
            }
        }
        list.distinctBy { it.name }.take(175) // Limit precisely to ~175 high quality items
    }

