package com.example.services.recommendation.knowledge.models

/**
 * Represents an intensity method used in training routines to stimulate muscle hypertrophy or strength.
 *
 * @property id Unique identifier for the intensity method.
 * @property name Descriptive name of the method (e.g., "Drop Set").
 * @property description Detailed description of how the method is executed.
 * @property recommendedGoals List of goal IDs for which this method is recommended.
 * @property contraindications Conditions under which this method should be avoided.
 * @property fatigueMultiplier Multiplier factor of fatigue generated by this method relative to standard sets.
 * @property timeCostMinutes Additional time cost in minutes per exercise when using this method.
 * @property recommendedExerciseTypes Recommended types of exercises (e.g., Compound, Isolation).
 * @property recommendedLevel Minimum recommended training experience level (e.g., Beginner, Advanced).
 * @property allowCompound Whether this method is safe and allowed for compound exercises.
 * @property allowIsolation Whether this method is safe and allowed for isolation exercises.
 */
data class IntensityMethod(
    val id: String,
    val name: String,
    val description: String,
    val recommendedGoals: List<String>,
    val contraindications: String,
    val fatigueMultiplier: Double,
    val timeCostMinutes: Int,
    val recommendedExerciseTypes: List<String>,
    val recommendedLevel: String,
    val allowCompound: Boolean,
    val allowIsolation: Boolean
)
